$mpv = $null
if ($Shortcuts) {
  $NoSync = [switch]$true
  $NoVendor = [switch]$true
  Say 'solo accesos directos y enlaces mpv-uos:// (sin comprobar requisitos, ni uv sync, ni vendor)'
} else {
  $missing = @()
  $mpv = Get-Command -Name mpv -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
  if (-not $mpv) {
    # El instalador de shinchiro.mpv (winget) deja mpv en Program Files\MPV Player sin tocar el PATH.
    $cands = @()
    if ($env:ProgramFiles) { $cands += (Join-Path (Join-Path $env:ProgramFiles 'MPV Player') 'mpv.exe') }
    if (${env:ProgramFiles(x86)}) { $cands += (Join-Path (Join-Path ${env:ProgramFiles(x86)} 'MPV Player') 'mpv.exe') }
    foreach ($cand in $cands) {
      if (Test-Path -LiteralPath $cand -PathType Leaf) {
        $mpv = [pscustomobject]@{ Path = $cand; Name = 'mpv.exe' }
        break
      }
    }
  }
  if (-not $mpv) { $missing += 'mpv (>= 0.41): winget install --id shinchiro.mpv --exact  ·  o con scoop: scoop bucket add extras; scoop install mpv' }
  foreach ($tool in @('ffmpeg', 'ffprobe')) {
    if (-not (Get-Command -Name $tool -CommandType Application -ErrorAction SilentlyContinue)) {
      $missing += "${tool}: winget install Gyan.FFmpeg  ·  o: scoop install ffmpeg"
    }
  }
  if (-not $NoSync -and -not (Get-Command -Name uv -CommandType Application -ErrorAction SilentlyContinue)) {
    $missing += 'uv: winget install astral-sh.uv  ·  o: https://docs.astral.sh/uv/'
  }
  if ($missing.Count -gt 0) {
    [Console]::Error.WriteLine('Faltan programas en el PATH:')
    foreach ($m in $missing) { [Console]::Error.WriteLine("  - $m") }
    [Console]::Error.WriteLine('Instálalos, abre una terminal nueva (para que se lea el PATH) y repite.')
    exit 1
  }
  $ver = Get-MuMpvVersion -Mpv $mpv.Path
  if ($ver -and $ver[0] -eq 0 -and $ver[1] -lt 41) { Say "aviso: mpv $($ver[0]).$($ver[1]) < 0.41; algunas funciones no irán" }
}

# -- python env + vendored third parties ------------------------------------------------------------------------------
if (-not $NoSync) {
  $uvArgs = @('sync', '--project', $Root)
  if ($Extras) { $uvArgs += @('--extra', 'translate', '--extra', 'semantic', '--extra', 'impersonate') }
  Say ('uv ' + ($uvArgs -join ' '))
  Step 'uv-sync' $Root ($uvArgs -join ' ') {
    & uv @uvArgs
    if ($LASTEXITCODE -ne 0) { throw "uv sync terminó con código $LASTEXITCODE" }
  }
}
if (-not $NoVendor) {
  $lock = Read-MuVendorLock -Path $LockPath
  Say "binarios de terceros (vendor.lock, verificados con SHA-256) en $VendorDir"
  Step 'vendor-ziggy' (Join-Path $Root 'mpv-config\scripts\uosc\bin\ziggy-windows.exe') (Get-MuLockValue $lock 'UOSC_ZIP_URL') {
    Install-MuZiggy -Lock $lock -VendorDir $VendorDir -ConfigDir (Join-Path $Root 'mpv-config')
  }
  $ytBase = $env:MPV_UOS_YTDLP_BASE_URL
  Step 'vendor-yt-dlp' (Join-Path $VendorDir 'bin\yt-dlp.exe') ('yt-dlp ' + (Get-MuLockValue $lock 'YTDLP_VERSION') + ' + SHA2-256SUMS') {
    Install-MuYtDlp -Lock $lock -VendorDir $VendorDir -BaseUrl $ytBase -Force:$Force
  }
  if (Test-Path -LiteralPath (Join-Path $VendorDir 'bin\deno.exe') -PathType Leaf) {
    Say 'deno: presente (vendor\bin\deno.exe)'
  } elseif (Test-MuJsRuntime) {
    Say 'deno: no necesario (hay deno o node >= 22 en el PATH)'
  } else {
    Step 'vendor-deno' (Join-Path $VendorDir 'bin\deno.exe') (Get-MuLockValue $lock 'DENO_VERSION') {
      Install-MuDeno -Lock $lock -VendorDir $VendorDir
    }
  }
  if ($Whisper) {
    Step 'vendor-whisper' (Join-Path $VendorDir 'whisper\bin\whisper-cli.exe') (Get-MuLockValue $lock 'WHISPER_WIN_URL') {
      Install-MuWhisper -Lock $lock -VendorDir $VendorDir
    }
  }
}

