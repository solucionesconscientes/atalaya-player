if (-not $NoProtocol) {
  $cmdLine = "`"$psExe`" " + (Get-MuShellArguments -Root $Root -WithUrl)
  Say 'enlaces mpv-uos:// (Mis notas, «Enviar a MPV-UOS» del navegador) → MPV-UOS'
  Step 'register-protocol' $PROTOCOL_KEY $cmdLine {
    if (-not $OnWindows) { return 'omitido (no es Windows)' }
    if (Test-Path -LiteralPath $PROTOCOL_KEY) {
      $marker = (Get-ItemProperty -LiteralPath $PROTOCOL_KEY -ErrorAction SilentlyContinue).PSObject.Properties['MPVUOSInstaller']
      if (-not ($marker -and $marker.Value -eq $MARK)) { return 'ya existe y no es de MPV-UOS: se deja' }
    }
    $null = New-Item -Force -Path "$PROTOCOL_KEY\shell\open\command"
    Set-ItemProperty -LiteralPath $PROTOCOL_KEY -Name '(default)' -Value "URL:$AppName"
    Set-ItemProperty -LiteralPath $PROTOCOL_KEY -Name 'URL Protocol' -Value ''
    Set-ItemProperty -LiteralPath $PROTOCOL_KEY -Name 'MPVUOSInstaller' -Value $MARK
    Set-ItemProperty -LiteralPath "$PROTOCOL_KEY\shell\open\command" -Name '(default)' -Value $cmdLine
  }

  # «Abrir con Atalaya» en el menú contextual de los formatos de vídeo y audio. No cambia el programa
  # predeterminado: Windows exige que eso lo elija el usuario, y hacerlo por la espalda es de mala educación.
  $ProgIdKey = "HKCU:\Software\Classes\$FILE_PROGID"
  # Windows 11 no enseña en «Abrir con» un ProgID suelto: hace falta una entrada en
  # Applications\<algo>.exe con un ejecutable real. Atalaya.exe es el lanzador GUI del paquete.
  $appExe = Join-Path (Join-Path $Root 'bin') 'Atalaya.exe'
  $appCmd = if (Test-Path -LiteralPath $appExe -PathType Leaf) { "`"$appExe`" `"%1`"" } else { $cmdLine }
  Say 'añadiendo Atalaya a «Abrir con» (vídeo y audio)'
  Step 'register-fileassoc' $ProgIdKey $appCmd {
    if (-not $OnWindows) { return 'omitido (no es Windows)' }
    $null = New-Item -Force -Path "$ProgIdKey\shell\open\command"
    Set-ItemProperty -LiteralPath $ProgIdKey -Name '(default)' -Value 'Vídeo o audio (Atalaya Player)'
    Set-ItemProperty -LiteralPath $ProgIdKey -Name 'MPVUOSInstaller' -Value $MARK
    $iconExe = Join-Path (Join-Path $Root 'mpv') 'mpv.exe'
    $iconPath = if ($IconPath -and (Test-Path -LiteralPath $IconPath)) { $IconPath } elseif (Test-Path -LiteralPath $iconExe) { $iconExe } elseif (Test-Path -LiteralPath $appExe) { $appExe } else { $psExe }
    $null = New-Item -Force -Path "$ProgIdKey\DefaultIcon"
    Set-ItemProperty -LiteralPath "$ProgIdKey\DefaultIcon" -Name '(default)' -Value "$iconPath,0"
    Set-ItemProperty -LiteralPath "$ProgIdKey\shell\open\command" -Name '(default)' -Value $appCmd
    foreach ($e in $FILE_EXTS) {
      $k = "HKCU:\Software\Classes\$e\OpenWithProgids"
      $null = New-Item -Force -Path $k
      $null = New-ItemProperty -Path $k -Name $FILE_PROGID -Value ([byte[]]@()) -PropertyType Binary -Force
    }
    if (Test-Path -LiteralPath $appExe -PathType Leaf) {
      $appsKey = "HKCU:\Software\Classes\Applications\Atalaya.exe"
      $null = New-Item -Force -Path "$appsKey\shell\open\command"
      Set-ItemProperty -LiteralPath $appsKey -Name 'FriendlyAppName' -Value $AppName
      Set-ItemProperty -LiteralPath $appsKey -Name 'ApplicationCompany' -Value 'Soluciones Conscientes'
      Set-ItemProperty -LiteralPath $appsKey -Name 'ApplicationIcon' -Value "$appExe,0"
      Set-ItemProperty -LiteralPath $appsKey -Name 'MPVUOSInstaller' -Value $MARK
      Set-ItemProperty -LiteralPath "$appsKey\shell\open\command" -Name '(default)' -Value $appCmd
      foreach ($e in $FILE_EXTS) {
        $null = New-Item -Force -Path "$appsKey\SupportedTypes"
        $null = New-ItemProperty -Path "$appsKey\SupportedTypes" -Name $e -Value '' -PropertyType String -Force
      }
    }
    return "«Abrir con» en $($FILE_EXTS.Count) formatos"
  }
}

