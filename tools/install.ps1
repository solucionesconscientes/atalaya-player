$script:Actions = New-Object System.Collections.ArrayList
$script:Failed = 0
function Say { param([string]$Text) Write-Host "• $Text" }
function Step {
  # Record an action; run it unless -DryRun. A failing step is reported and counted, the install goes on.
  param([string]$Action, [string]$Target, [string]$Detail = '', [scriptblock]$Do = $null)
  $null = $script:Actions.Add([ordered]@{ action = $Action; target = $Target; detail = $Detail })
  if ($DryRun -or $null -eq $Do) { return }
  try {
    $r = & $Do
    if ($r) { Say "  $Action`: $r" }
  } catch {
    $script:Failed++
    Write-Warning "$Action ($Target): $($_.Exception.Message)"
  }
}
function Finish {
  param([int]$Code)
  if ($DryRun) {
    $mode = 'install'
    if ($Uninstall) { $mode = 'uninstall' }
    [ordered]@{ mode = $mode; root = $Root; install_dir = $InstallDir; actions = @($script:Actions) } | ConvertTo-Json -Compress -Depth 5
  }
  exit $Code
}

function Read-MuState {
  if (Test-Path -LiteralPath $StatePath -PathType Leaf) {
    try { return (Get-Content -Raw -LiteralPath $StatePath | ConvertFrom-Json) } catch { }
  }
  return $null
}

# -- uninstall --------------------------------------------------------------------------------------------------------
if ($Uninstall) {
  # Only what this script created: the launcher carries the marker line, the shortcut must point to a
  # bin\mpv-uos.ps1 and be listed in install.json, the mpv-uos:// key carries the MPVUOSInstaller value.
  $state = Read-MuState
  if ((Test-Path -LiteralPath $Launcher -PathType Leaf)) {
    if ((Get-Content -Raw -LiteralPath $Launcher).Contains($MARK)) {
      Say "borrando $Launcher"
      Step 'remove-launcher' $Launcher '' { Remove-Item -Force -LiteralPath $Launcher }
    } else { Say "no es de MPV-UOS, se deja: $Launcher" }
  }
  $lnks = @($Shortcut)
  if ($state -and $state.PSObject.Properties['shortcut'] -and $state.shortcut) { $lnks += [string]$state.shortcut }
  foreach ($lnk in ($lnks | Select-Object -Unique)) {
    if (-not (Test-Path -LiteralPath $lnk -PathType Leaf)) { continue }
    $ours = $state -and $state.PSObject.Properties['shortcut'] -and ([string]$state.shortcut -eq $lnk)
    if ($ours -and $OnWindows) {
      try { $ours = (New-Object -ComObject WScript.Shell).CreateShortcut($lnk).Arguments -like '*mpv-uos.ps1*' } catch { $ours = $false }
    }
    if ($ours) {
      Say "borrando $lnk"
      Step 'remove-shortcut' $lnk '' { Remove-Item -Force -LiteralPath $lnk }
    } else { Say "no es de MPV-UOS, se deja: $lnk" }
  }
  if ($OnWindows -and (Test-Path -LiteralPath $PROTOCOL_KEY)) {
    $marker = (Get-ItemProperty -LiteralPath $PROTOCOL_KEY -ErrorAction SilentlyContinue).PSObject.Properties['MPVUOSInstaller']
    if ($marker -and $marker.Value -eq $MARK) {
      Say 'quitando los enlaces mpv-uos://'
      Step 'remove-protocol' $PROTOCOL_KEY '' { Remove-Item -Recurse -Force -LiteralPath $PROTOCOL_KEY }
    } else { Say "no es de MPV-UOS, se deja: $PROTOCOL_KEY" }
  }
  if (Test-Path -LiteralPath $StatePath -PathType Leaf) {
    Step 'remove-state' $StatePath '' { Remove-Item -Force -LiteralPath $StatePath }
  }
  Step 'remove-empty-dirs' $InstallDir '' {
    foreach ($d in @((Join-Path $InstallDir 'bin'), $InstallDir)) {
      if ((Test-Path -LiteralPath $d) -and -not (Get-ChildItem -Force -LiteralPath $d)) { Remove-Item -Force -LiteralPath $d }
    }
  }
  Say 'desinstalado (el checkout, vendor\ y los datos de usuario en %APPDATA%\mpv-uos no se tocan)'
  Finish 0
}

