function New-MuShortcut {
  # One .lnk, with the same target and arguments, for the Start menu and for the Desktop.
  param([string]$Path, [string]$PsExe, [string]$Arguments, [string]$IconSource)
  $null = New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Path)
  $ws = New-Object -ComObject WScript.Shell
  $s = $ws.CreateShortcut($Path)
  $s.TargetPath = $PsExe
  $s.Arguments = $Arguments
  $s.WorkingDirectory = $HOME
  $s.Description = "$AppName · reproductor multimedia"
  $s.WindowStyle = 7   # minimised: the hidden PowerShell only flashes briefly
  $s.IconLocation = "$IconSource,0"
  $s.Save()
}

$script:Actions = New-Object System.Collections.ArrayList
$script:Failed = 0
function Say {
  # Host output, and the same line in the log: Start-Transcript does not always capture Write-Host when the
  # caller redirects the streams (the .exe does), and a failure that leaves no trace cannot be diagnosed.
  param([string]$Text)
  Write-Host "• $Text"
  if ($Log) { try { Add-Content -LiteralPath $Log -Value "• $Text" -Encoding utf8 } catch { } }
}
function Step {
  # Record an action; run it unless -DryRun. A failing step is reported and counted, the install goes on.
  param([string]$Action, [string]$Target, [string]$Detail = '', [scriptblock]$Do = $null)
  $null = $script:Actions.Add([ordered]@{ action = $Action; target = $Target; detail = $Detail })
  if ($Log) { try { Add-Content -LiteralPath $Log -Value "paso ${Action}: $Target" -Encoding utf8 } catch { } }
  if ($DryRun -or $null -eq $Do) { return }
  try {
    $r = & $Do
    if ($r) { Say "  $Action`: $r" }
  } catch {
    $script:Failed++
    Write-Warning "$Action ($Target): $($_.Exception.Message)"
    if ($Log) { try { Add-Content -LiteralPath $Log -Value "FALLO $Action ($Target): $($_.Exception.Message)" -Encoding utf8 } catch { } }
  }
}
function Finish {
  param([int]$Code)
  if ($DryRun) {
    $mode = 'install'
    if ($Uninstall) { $mode = 'uninstall' }
    [ordered]@{ mode = $mode; root = $Root; install_dir = $InstallDir; actions = @($script:Actions) } | ConvertTo-Json -Compress -Depth 5
  }
  exit $Code
}

