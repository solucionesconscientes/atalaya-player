    if (Test-Path -LiteralPath $PROTOCOL_KEY) {
      $marker = (Get-ItemProperty -LiteralPath $PROTOCOL_KEY -ErrorAction SilentlyContinue).PSObject.Properties['MPVUOSInstaller']
      if (-not ($marker -and $marker.Value -eq $MARK)) { return 'ya existe y no es de MPV-UOS: se deja' }
    }
    $null = New-Item -Force -Path "$PROTOCOL_KEY\shell\open\command"
    Set-ItemProperty -LiteralPath $PROTOCOL_KEY -Name '(default)' -Value "URL:$AppName"
    Set-ItemProperty -LiteralPath $PROTOCOL_KEY -Name 'URL Protocol' -Value ''
    Set-ItemProperty -LiteralPath $PROTOCOL_KEY -Name 'MPVUOSInstaller' -Value $MARK
    Set-ItemProperty -LiteralPath "$PROTOCOL_KEY\shell\open\command" -Name '(default)' -Value $cmdLine
  }
}

Step 'write-state' $StatePath '' {
  $state = [ordered]@{ marker = $MARK; root = $Root; launcher = $Launcher; shortcut = $Shortcut; protocol = (-not $NoProtocol) }
  [System.IO.File]::WriteAllText($StatePath, ($state | ConvertTo-Json -Depth 3))
}

