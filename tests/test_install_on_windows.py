@pytest.mark.network
@pytest.mark.timeout(1800)
def test_the_vendored_windows_binaries_download_and_verify(shell: str, tmp_path: Path, protocol_key):
    """The whole chain against the real GitHub releases: SHA-256 from vendor.lock, SHA2-256SUMS for yt-dlp."""
    lock = vendor_lock()
    env = install_env(tmp_path)
    installer(shell, "-NoSync", "-Whisper", env=env, timeout=1500)

    ziggy = ROOT / "mpv-config" / "scripts" / "uosc" / "bin" / "ziggy-windows.exe"
    ytdlp = ROOT / "vendor" / "bin" / "yt-dlp.exe"
    whisper = ROOT / "vendor" / "whisper" / "bin" / "whisper-cli.exe"
    for exe in (ziggy, ytdlp, whisper):
        assert exe.is_file(), exe
        assert exe.read_bytes()[:2] == b"MZ", f"{exe} is not a Windows executable"
    assert list((ROOT / "vendor" / "whisper" / "bin").glob("*.dll")), "whisper-cli.exe needs its DLLs next to it"
    assert Path(str(ytdlp) + ".version").read_text(encoding="utf-8").strip() == lock["YTDLP_VERSION"]
    version = subprocess.run([str(ytdlp), "--version"], capture_output=True, text=True, timeout=300)
    assert version.returncode == 0 and version.stdout.strip() == lock["YTDLP_VERSION"]

    # second pass: everything is already there and verified, so nothing is downloaded again
    again = installer(shell, "-NoSync", "-Whisper", env=env, timeout=600)
    assert "cached" in again.stdout and "present" in again.stdout
