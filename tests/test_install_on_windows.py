def test_the_registered_command_really_opens_a_url(shell: str, tmp_path: Path, installed):
    """The exact command line Windows will run for mpv-uos://, with -DryRun added so no window opens."""
    env, _ = installed
    # ASCII on purpose: Windows PowerShell 5.1 writes stdout in the console code page, so reading accents back
    # through a pipe would test this harness and not the installer. The accented path is played for real below.
    media = r"C:\Videos\mi peli (2024).mkv"
    url = "mpv-uos://open?path=" + urllib.parse.quote(media, safe="")
    command = protocol_values()["command"].replace('"%1"', f'"{url}"') + " -DryRun"
    out = subprocess.run(command, capture_output=True, text=True, encoding="utf-8", errors="replace",
                         env={**env, "MPV_UOS_DATA_DIR": str(tmp_path / "data")}, timeout=300)
    assert out.returncode == 0, f"{command}\nstdout:\n{out.stdout}\nstderr:\n{out.stderr}"
    got = last_json(out.stdout)
    assert got["mpv"][0] == "mpv" and media in got["mpv"]
    assert got["mpv"][1] == f"--config-dir={ROOT / 'mpv-config'}"
    assert got["pipe"].startswith(PIPE_PREFIX)
    assert not (tmp_path / "data").exists()          # -DryRun creates nothing


