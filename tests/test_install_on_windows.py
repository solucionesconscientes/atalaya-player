# -- helpers -----------------------------------------------------------------------------------------------------


def run(shell: str, args: list[str], env: dict[str, str] | None = None, check: bool = True,
        timeout: float = 300) -> subprocess.CompletedProcess[str]:
    out = subprocess.run([shell, "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", *args],
                         capture_output=True, text=True, encoding="utf-8", errors="replace",
                         env=env, timeout=timeout)
    if check and out.returncode != 0:
        raise AssertionError(f"{Path(shell).name} {args[:3]} -> {out.returncode}\n"
                             f"stdout:\n{out.stdout}\nstderr:\n{out.stderr}")
    return out


def installer(shell: str, *args: str, env: dict[str, str] | None = None, check: bool = True,
              timeout: float = 300) -> subprocess.CompletedProcess[str]:
    return run(shell, ["-File", str(INSTALL), *args], env=env, check=check, timeout=timeout)


def last_json(text: str):
    return json.loads(text.strip().splitlines()[-1])


def plan_actions(plan: dict) -> dict[str, dict]:
    return {a["action"]: a for a in plan["actions"]}


def install_env(tmp_path: Path, **extra: str) -> dict[str, str]:
    """The real environment plus a throwaway install dir and Start menu: a test never writes where a user has it."""
    env = os.environ.copy()
    env.pop("MPV_UOS_MPV", None)                    # the mpv under test is the one on the PATH, as a user has it
    overrides = {"MPV_UOS_INSTALL_DIR": str(tmp_path / "inst"), "MPV_UOS_START_MENU_DIR": str(tmp_path / "menu")}
    overrides.update(extra)
    for name, value in overrides.items():
        # Windows environment variables are case insensitive ("Path"), and two spellings of one name in the same
        # block is undefined: drop whatever case the parent had before setting ours.
        for inherited in [k for k in env if k.upper() == name.upper()]:
            env.pop(inherited)
        env[name] = value
    return env


def vendor_lock() -> dict[str, str]:
    lock = {}
    for line in (ROOT / "vendor.lock").read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            lock[key] = value
    return lock


def shortcut_properties(shell: str, lnk: Path) -> dict[str, object]:
    """Read a .lnk back through WScript.Shell, the same COM object the installer wrote it with."""
    quoted = str(lnk).replace("'", "''")
    script = (f"$s = (New-Object -ComObject WScript.Shell).CreateShortcut('{quoted}'); "
              "[ordered]@{ target = $s.TargetPath; arguments = $s.Arguments; icon = $s.IconLocation; "
              "style = $s.WindowStyle; description = $s.Description; workdir = $s.WorkingDirectory } | "
              "ConvertTo-Json -Compress")
    return last_json(run(shell, ["-Command", script]).stdout)


def protocol_values() -> dict[str, str] | None:
    """The values of HKCU\\Software\\Classes\\mpv-uos plus its open command, or None when the key is not there."""
    try:
        key = winreg.OpenKey(winreg.HKEY_CURRENT_USER, PROTOCOL_SUBKEY)
    except FileNotFoundError:
        return None
    with key:
        values: dict[str, str] = {}
        i = 0
        while True:
            try:
                name, value, _ = winreg.EnumValue(key, i)
            except OSError:
                break
            values[name or "(default)"] = value
            i += 1
        try:
            with winreg.OpenKey(key, r"shell\open\command") as command:
                values["command"] = winreg.QueryValueEx(command, "")[0]
        except FileNotFoundError:
            pass
        return values


def delete_protocol_key() -> None:
    for sub in (r"shell\open\command", r"shell\open", "shell", ""):
        path = PROTOCOL_SUBKEY + ("\\" + sub if sub else "")
        try:
            winreg.DeleteKey(winreg.HKEY_CURRENT_USER, path)
        except OSError:
            pass


@pytest.fixture()
def protocol_key():
    """HKCU is shared with the person using the machine: a foreign mpv-uos:// handler stops the test instead of
    being overwritten, and whatever the installer registers here is removed afterwards."""
    before = protocol_values()
    if before is not None:
        if before.get("MPVUOSInstaller") != MARK:
            pytest.skip(f"{PROTOCOL_KEY} already exists and was not made by MPV-UOS: left untouched")
        delete_protocol_key()           # ours, left over from an interrupted run
    yield
    after = protocol_values()
    if after is not None and after.get("MPVUOSInstaller") == MARK:
        delete_protocol_key()


