def test_install_leaves_a_foreign_protocol_handler_alone(shell: str, tmp_path: Path):
    """Somebody else's mpv-uos:// (or a leftover from another program): it is reported and kept, never replaced."""
    if protocol_values() is not None:
        pytest.skip(f"{PROTOCOL_KEY} already exists: not touching it")
    key = winreg.CreateKey(winreg.HKEY_CURRENT_USER, PROTOCOL_SUBKEY)
    try:
        with key:
            winreg.SetValueEx(key, None, 0, winreg.REG_SZ, "URL:otro programa")
        out = installer(shell, "-NoSync", "-NoVendor", env=install_env(tmp_path))
        assert "no es de MPV-UOS" in out.stdout
        values = protocol_values()
        assert values["(default)"] == "URL:otro programa"
        assert "MPVUOSInstaller" not in values and "command" not in values
    finally:
        delete_protocol_key()


