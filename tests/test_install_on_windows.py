"""H28 · tools/install.ps1 and bin/mpv-uos.cmd on a REAL Windows: what Linux cannot prove.

tests/test_windows_scripts.py runs the same scripts with pwsh 7 on Linux, where there is no Start menu, no
WScript.Shell, no registry and no Windows PowerShell 5.1, so it stops exactly where this file starts: the .lnk is
read back through COM, the mpv-uos:// handler is read back from HKCU and run as the system would run it, the
launcher goes through the real powershell.exe 5.1, and the Windows folders (%LOCALAPPDATA%, the Programs folder)
are the real ones. Everything is skipped off Windows (docs/PLATAFORMAS.md).

Every test installs into its own temporary folder (MPV_UOS_INSTALL_DIR / MPV_UOS_START_MENU_DIR), so nothing here
touches a real installation. The one piece of shared state is HKCU\\Software\\Classes\\mpv-uos, which the
``protocol_key`` fixture leaves as it found it; a key that is not ours is never modified, not even in a test.

Run it on Windows with:  uv run pytest tests/test_install_on_windows.py -v
and the download tests with: uv run pytest tests/test_install_on_windows.py -v -m network
"""

